type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const stored = window.localStorage.getItem("fasalflux-language");
    return stored === "hi" || stored === "te" || stored === "pa"
      ? stored
      : "en";
  });

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem("fasalflux-language", next);
    document.documentElement.lang =
      next === "hi" ? "hi" : next === "te" ? "te" : next === "pa" ? "pa" : "en";
  };

  useEffect(() => {
    document.documentElement.lang =
      language === "hi"
        ? "hi"
        : language === "te"
          ? "te"
          : language === "pa"
            ? "pa"
            : "en";
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (key: string, values?: Record<string, string | number>) => {
        let output = messages[language][key] ?? key;
        Object.entries(values ?? {}).forEach(([name, replacement]) => {
          output = output.replace(`{{${name}}}`, String(replacement));
        });
        return output;
      },
    }),
    [language],
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context)
    throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
